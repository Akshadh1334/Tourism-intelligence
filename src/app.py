import streamlit as st
import pandas as pd
import json
import os
from PIL import Image

# ---------------------------------------------------------
# Page Configuration
# ---------------------------------------------------------
st.set_page_config(
    page_title="Tourism Intelligence Dashboard",
    page_icon="✈️",
    layout="wide"
)

st.title("✈️ Smart Tourism Intelligence Dashboard")
st.markdown("Automated analytics pipeline for demand forecasting, dynamic pricing, sentiment analysis, and destination recommendations.")

# ---------------------------------------------------------
# Sidebar Navigation
# ---------------------------------------------------------
st.sidebar.header("Navigation")
page = st.sidebar.radio(
    "Choose a View:",
    ["📊 Analytics Overview", "🔍 Destination Lookup", "🎯 Travel Recommender", "⚙️ Run Pipeline"]
)

# Load summary JSON if available
SUMMARY_FILE = "results/summary.json"
summary_data = {}
if os.path.exists(SUMMARY_FILE):
    with open(SUMMARY_FILE, "r") as f:
        summary_data = json.load(f)

# ---------------------------------------------------------
# Page 1: Analytics Overview & Visualizations
# ---------------------------------------------------------
if page == "📊 Analytics Overview":
    st.header("Pipeline Visualizations")
    st.write("Visual outputs automatically generated by the underlying machine learning models.")

    col1, col2 = st.columns(2)

    with col1:
        st.subheader("1. Anomaly Detection & Market Shocks")
        if os.path.exists("results/anomalies.png"):
            st.image("results/anomalies.png", use_column_width=True)
        else:
            st.info("Run the pipeline (`python main.py --regen`) to generate `anomalies.png`.")

        st.subheader("2. Destination Clusters (K-Means + PCA)")
        if os.path.exists("results/segments.png"):
            st.image("results/segments.png", use_column_width=True)
        else:
            st.info("Run the pipeline (`python main.py --regen`) to generate `segments.png`.")

    with col2:
        st.subheader("3. Dynamic Pricing Strategy")
        if os.path.exists("results/pricing.png"):
            st.image("results/pricing.png", use_column_width=True)
        else:
            st.info("Run the pipeline (`python main.py --regen`) to generate `pricing.png`.")

        st.subheader("4. Aspect-Based Sentiment Scores")
        if os.path.exists("results/aspect_sentiment.png"):
            st.image("results/aspect_sentiment.png", use_column_width=True)
        else:
            st.info("Run the pipeline (`python main.py --regen`) to generate `aspect_sentiment.png`.")

    st.subheader("5. Demand Forecast Grid")
    if os.path.exists("results/forecast_grid.png"):
        st.image("results/forecast_grid.png", use_column_width=True)

# ---------------------------------------------------------
# Page 2: Destination Lookup
# ---------------------------------------------------------
elif page == "🔍 Destination Lookup":
    st.header("Explore Destination Insights")

    # Load forecasted data if available
    FORECAST_FILE = "results/forecast_next_12_months.csv"
    PRICING_FILE = "results/pricing_plan.csv"

    if os.path.exists(FORECAST_FILE) and os.path.exists(PRICING_FILE):
        df_forecast = pd.read_csv(FORECAST_FILE)
        df_pricing = pd.read_csv(PRICING_FILE)

        places = df_forecast["place"].unique() if "place" in df_forecast.columns else ["Goa", "Pondicherry", "Chennai"]
        selected_place = st.selectbox("Select a Destination:", places)

        st.subheader(f"Forecast & Pricing Action for {selected_place}")
        place_forecast = df_forecast[df_forecast["place"] == selected_place] if "place" in df_forecast.columns else df_forecast
        st.dataframe(place_forecast, use_container_width=True)
    else:
        st.warning("Prediction outputs not found in `results/`. Please run the pipeline first.")

# ---------------------------------------------------------
# Page 3: Travel Recommender
# ---------------------------------------------------------
elif page == "🎯 Travel Recommender":
    st.header("Find Matching Destinations")
    st.write("Score your travel preferences from 1 to 10 to receive recommendations based on vector similarity.")

    col1, col2, col3 = st.columns(3)
    with col1:
        beach = st.slider("Beach / Coastal", 1, 10, 5)
        nightlife = st.slider("Nightlife / Entertainment", 1, 10, 5)
    with col2:
        budget = st.slider("Budget / Affordability", 1, 10, 5)
        nature = st.slider("Nature / Outdoors", 1, 10, 5)
    with col3:
        target_month = st.selectbox("Preferred Month of Visit:", list(range(1, 13)), index=11)

    if st.button("Get Recommendations"):
        try:
            from src.recommender import recommend
            # Mock travel prefs dict matching your backend recommender signature
            prefs = {"beach": beach, "nightlife": nightlife, "budget": budget, "nature": nature}
            results = recommend(prefs, month=target_month)
            st.subheader("Top Recommended Destinations")
            st.dataframe(results, use_container_width=True)
        except Exception as e:
            st.error(f"Could not compute recommendations: {e}")

# ---------------------------------------------------------
# Page 4: Run Pipeline
# ---------------------------------------------------------
elif page == "⚙️ Run Pipeline":
    st.header("Pipeline Execution Controls")
    st.write("Trigger the main analytics engine directly from the UI.")

    if st.button("🚀 Run Full Pipeline (`main.py --regen`)"):
        with st.spinner("Running models, anomaly detection, dynamic pricing, and rendering plots..."):
            os.system("python main.py --regen")
        st.success("Pipeline executed successfully! All graphs and CSVs in `results/` are updated.")
